-- Registra quién creó o corrigió datos desde la aplicación a partir de esta instalación.
BEGIN;
CREATE TABLE IF NOT EXISTS auditoria_cambios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id BIGINT,
    nombre_usuario VARCHAR(60),
    tabla VARCHAR(80) NOT NULL,
    registro VARCHAR(100) NOT NULL,
    operacion VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT','UPDATE','DELETE'))
);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha ON auditoria_cambios(fecha DESC, id DESC);

CREATE OR REPLACE FUNCTION registrar_cambio_granja() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    actor BIGINT;
    fila JSONB;
BEGIN
    actor := NULLIF(current_setting('granja.actor_id', true), '')::BIGINT;
    fila := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
    INSERT INTO auditoria_cambios(usuario_id,nombre_usuario,tabla,registro,operacion)
    VALUES (actor, (SELECT nombre_usuario FROM usuarios WHERE id=actor), TG_TABLE_NAME,
            COALESCE(fila ->> TG_ARGV[0], '?'), TG_OP);
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DO $$
DECLARE
    entrada RECORD;
BEGIN
    FOR entrada IN
        SELECT * FROM (VALUES
            ('usuarios','id'), ('contactos','id'), ('ubicaciones','id'), ('lotes','id'),
            ('animales','id'), ('bajas_animales','id'), ('movimientos_animales','id'),
            ('pesajes','id'), ('servicios_reproductivos','id'), ('diagnosticos_gestacion','id'),
            ('partos','id'), ('crias_parto','cria_id'), ('insumos','id'),
            ('movimientos_inventario','id'), ('alimentaciones','id'),
            ('eventos_sanitarios','id'), ('ventas','id'), ('detalle_ventas','id'),
            ('movimientos_financieros','id')
        ) AS t(tabla, clave)
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS auditoria_cambio ON %I', entrada.tabla);
        EXECUTE format('CREATE TRIGGER auditoria_cambio AFTER INSERT OR UPDATE OR DELETE ON %I '
                       || 'FOR EACH ROW EXECUTE FUNCTION registrar_cambio_granja(%L)',
                       entrada.tabla, entrada.clave);
    END LOOP;
END;
$$;
COMMIT;
