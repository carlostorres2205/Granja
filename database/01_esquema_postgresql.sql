-- Granja: esquema inicial para PostgreSQL 18.
-- Ejecutar en Query Tool conectado a la base de datos Granja.
-- No incluye DROP ni datos de ejemplo. Es seguro repetirlo sobre un esquema vacío.
BEGIN;

CREATE TABLE IF NOT EXISTS configuracion_granja (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    nombre VARCHAR(120) NOT NULL,
    ubicacion VARCHAR(200),
    telefono VARCHAR(30),
    moneda VARCHAR(3) NOT NULL DEFAULT 'NIO',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    nombre_usuario VARCHAR(60) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMINISTRADOR', 'ENCARGADO', 'TRABAJADOR')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contactos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PROVEEDOR', 'COMPRADOR', 'VETERINARIO', 'OTRO')),
    telefono VARCHAR(30),
    correo VARCHAR(150),
    direccion VARCHAR(250),
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS ubicaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('POTRERO', 'CORRAL', 'ENFERMERIA', 'OTRO')),
    capacidad INTEGER CHECK (capacidad IS NULL OR capacidad > 0),
    superficie_hectareas NUMERIC(10,2) CHECK (superficie_hectareas IS NULL OR superficie_hectareas > 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    proposito VARCHAR(20) NOT NULL CHECK (proposito IN ('ENGORDE', 'REPRODUCCION', 'CRIANZA', 'OTRO')),
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS animales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arete VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100),
    sexo CHAR(1) NOT NULL CHECK (sexo IN ('M', 'H')),
    raza VARCHAR(100),
    fecha_nacimiento DATE,
    fecha_ingreso DATE NOT NULL,
    origen VARCHAR(20) NOT NULL CHECK (origen IN ('NACIDO', 'COMPRADO', 'OTRO')),
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO', 'VENDIDO', 'FALLECIDO', 'DESCARTADO')),
    madre_id BIGINT REFERENCES animales(id) ON DELETE RESTRICT,
    padre_id BIGINT REFERENCES animales(id) ON DELETE RESTRICT,
    lote_id BIGINT REFERENCES lotes(id) ON DELETE SET NULL,
    ubicacion_id BIGINT REFERENCES ubicaciones(id) ON DELETE SET NULL,
    peso_inicial_kg NUMERIC(8,2) CHECK (peso_inicial_kg IS NULL OR peso_inicial_kg > 0),
    precio_compra NUMERIC(14,2) CHECK (precio_compra IS NULL OR precio_compra >= 0),
    contacto_origen_id BIGINT REFERENCES contactos(id) ON DELETE SET NULL,
    observaciones TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (madre_id IS NULL OR madre_id <> id),
    CHECK (padre_id IS NULL OR padre_id <> id),
    CHECK (madre_id IS NULL OR padre_id IS NULL OR madre_id <> padre_id),
    CHECK (fecha_nacimiento IS NULL OR fecha_nacimiento <= fecha_ingreso)
);
CREATE INDEX IF NOT EXISTS idx_animales_estado_lote ON animales(estado, lote_id);
CREATE INDEX IF NOT EXISTS idx_animales_ubicacion ON animales(ubicacion_id);

CREATE TABLE IF NOT EXISTS movimientos_animales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT NOT NULL REFERENCES animales(id) ON DELETE RESTRICT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ubicacion_origen_id BIGINT REFERENCES ubicaciones(id) ON DELETE RESTRICT,
    ubicacion_destino_id BIGINT REFERENCES ubicaciones(id) ON DELETE RESTRICT,
    lote_origen_id BIGINT REFERENCES lotes(id) ON DELETE RESTRICT,
    lote_destino_id BIGINT REFERENCES lotes(id) ON DELETE RESTRICT,
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT,
    CHECK (ubicacion_destino_id IS NOT NULL OR lote_destino_id IS NOT NULL),
    CHECK (ubicacion_origen_id IS DISTINCT FROM ubicacion_destino_id
        OR lote_origen_id IS DISTINCT FROM lote_destino_id)
);
CREATE INDEX IF NOT EXISTS idx_mov_animales_animal_fecha ON movimientos_animales(animal_id, fecha DESC);

CREATE TABLE IF NOT EXISTS pesajes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT NOT NULL REFERENCES animales(id) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    peso_kg NUMERIC(8,2) NOT NULL CHECK (peso_kg > 0),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT,
    UNIQUE (animal_id, fecha)
);
CREATE INDEX IF NOT EXISTS idx_pesajes_fecha ON pesajes(fecha DESC);

CREATE TABLE IF NOT EXISTS servicios_reproductivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hembra_id BIGINT NOT NULL REFERENCES animales(id) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('MONTA', 'INSEMINACION')),
    macho_id BIGINT REFERENCES animales(id) ON DELETE RESTRICT,
    identificacion_semen VARCHAR(100),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT,
    CHECK (macho_id IS NULL OR macho_id <> hembra_id)
);
CREATE INDEX IF NOT EXISTS idx_servicios_hembra_fecha ON servicios_reproductivos(hembra_id, fecha DESC);

CREATE TABLE IF NOT EXISTS diagnosticos_gestacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hembra_id BIGINT NOT NULL REFERENCES animales(id) ON DELETE RESTRICT,
    servicio_id BIGINT REFERENCES servicios_reproductivos(id) ON DELETE SET NULL,
    fecha DATE NOT NULL,
    resultado VARCHAR(20) NOT NULL CHECK (resultado IN ('POSITIVO', 'NEGATIVO', 'INDETERMINADO')),
    fecha_parto_estimada DATE,
    veterinario_id BIGINT REFERENCES contactos(id) ON DELETE SET NULL,
    observaciones TEXT,
    CHECK (fecha_parto_estimada IS NULL OR fecha_parto_estimada >= fecha)
);
CREATE INDEX IF NOT EXISTS idx_diagnosticos_hembra_fecha ON diagnosticos_gestacion(hembra_id, fecha DESC);

CREATE TABLE IF NOT EXISTS partos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madre_id BIGINT NOT NULL REFERENCES animales(id) ON DELETE RESTRICT,
    servicio_id BIGINT REFERENCES servicios_reproductivos(id) ON DELETE SET NULL,
    fecha DATE NOT NULL,
    dificultad VARCHAR(20) CHECK (dificultad IN ('NORMAL', 'ASISTIDO', 'COMPLICADO')),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT
);
CREATE INDEX IF NOT EXISTS idx_partos_madre_fecha ON partos(madre_id, fecha DESC);

CREATE TABLE IF NOT EXISTS crias_parto (
    parto_id BIGINT NOT NULL REFERENCES partos(id) ON DELETE RESTRICT,
    cria_id BIGINT NOT NULL UNIQUE REFERENCES animales(id) ON DELETE RESTRICT,
    peso_nacimiento_kg NUMERIC(8,2) CHECK (peso_nacimiento_kg IS NULL OR peso_nacimiento_kg > 0),
    estado_nacimiento VARCHAR(20) NOT NULL DEFAULT 'VIVO'
        CHECK (estado_nacimiento IN ('VIVO', 'FALLECIDO')),
    PRIMARY KEY (parto_id, cria_id)
);

CREATE TABLE IF NOT EXISTS insumos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('ALIMENTO', 'MEDICAMENTO', 'SUPLEMENTO', 'OTRO')),
    unidad VARCHAR(20) NOT NULL,
    existencia NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (existencia >= 0),
    cantidad_minima NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_minima >= 0),
    costo_unitario NUMERIC(14,2) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
    fecha_vencimiento DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (nombre, unidad)
);

CREATE TABLE IF NOT EXISTS movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id BIGINT NOT NULL REFERENCES insumos(id) ON DELETE RESTRICT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    cantidad NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    -- En AJUSTE, usar signo positivo o negativo en cantidad_ajuste.
    cantidad_ajuste NUMERIC(14,3),
    costo_unitario NUMERIC(14,2) CHECK (costo_unitario IS NULL OR costo_unitario >= 0),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT,
    CHECK ((tipo = 'AJUSTE' AND cantidad_ajuste IS NOT NULL AND cantidad_ajuste <> 0)
        OR (tipo <> 'AJUSTE' AND cantidad_ajuste IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_mov_inventario_insumo_fecha ON movimientos_inventario(insumo_id, fecha DESC);

CREATE TABLE IF NOT EXISTS alimentaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lotes(id) ON DELETE RESTRICT,
    insumo_id BIGINT NOT NULL REFERENCES insumos(id) ON DELETE RESTRICT,
    fecha DATE NOT NULL,
    cantidad NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    costo_total NUMERIC(14,2) CHECK (costo_total IS NULL OR costo_total >= 0),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT
);
CREATE INDEX IF NOT EXISTS idx_alimentaciones_lote_fecha ON alimentaciones(lote_id, fecha DESC);

CREATE TABLE IF NOT EXISTS eventos_sanitarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT REFERENCES animales(id) ON DELETE RESTRICT,
    lote_id BIGINT REFERENCES lotes(id) ON DELETE RESTRICT,
    tipo VARCHAR(25) NOT NULL CHECK (tipo IN ('VACUNA', 'DESPARASITACION', 'ENFERMEDAD', 'TRATAMIENTO', 'REVISION', 'OTRO')),
    fecha DATE NOT NULL,
    descripcion TEXT NOT NULL,
    insumo_id BIGINT REFERENCES insumos(id) ON DELETE SET NULL,
    dosis VARCHAR(80),
    fecha_proxima DATE,
    fecha_fin_retiro DATE,
    veterinario_id BIGINT REFERENCES contactos(id) ON DELETE SET NULL,
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT,
    CHECK ((animal_id IS NOT NULL) <> (lote_id IS NOT NULL)),
    CHECK (fecha_proxima IS NULL OR fecha_proxima >= fecha),
    CHECK (fecha_fin_retiro IS NULL OR fecha_fin_retiro >= fecha)
);
CREATE INDEX IF NOT EXISTS idx_salud_animal_fecha ON eventos_sanitarios(animal_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_salud_proxima ON eventos_sanitarios(fecha_proxima);

CREATE TABLE IF NOT EXISTS tareas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    fecha_programada TIMESTAMPTZ NOT NULL,
    fecha_realizada TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    prioridad VARCHAR(10) NOT NULL DEFAULT 'MEDIA'
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    animal_id BIGINT REFERENCES animales(id) ON DELETE SET NULL,
    lote_id BIGINT REFERENCES lotes(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_tareas_estado_fecha ON tareas(estado, fecha_programada);

CREATE TABLE IF NOT EXISTS ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    comprador_id BIGINT REFERENCES contactos(id) ON DELETE SET NULL,
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS detalle_ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(id) ON DELETE RESTRICT,
    animal_id BIGINT NOT NULL UNIQUE REFERENCES animales(id) ON DELETE RESTRICT,
    peso_venta_kg NUMERIC(8,2) CHECK (peso_venta_kg IS NULL OR peso_venta_kg > 0),
    precio NUMERIC(14,2) NOT NULL CHECK (precio >= 0)
);
CREATE INDEX IF NOT EXISTS idx_detalle_ventas_venta ON detalle_ventas(venta_id);

CREATE TABLE IF NOT EXISTS movimientos_financieros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('INGRESO', 'GASTO')),
    categoria VARCHAR(30) NOT NULL CHECK (categoria IN ('VENTA_GANADO', 'COMPRA_GANADO', 'ALIMENTACION', 'SALUD', 'MANTENIMIENTO', 'SERVICIOS', 'OTRO')),
    concepto VARCHAR(200) NOT NULL,
    importe NUMERIC(14,2) NOT NULL CHECK (importe > 0),
    contacto_id BIGINT REFERENCES contactos(id) ON DELETE SET NULL,
    animal_id BIGINT REFERENCES animales(id) ON DELETE SET NULL,
    lote_id BIGINT REFERENCES lotes(id) ON DELETE SET NULL,
    venta_id BIGINT UNIQUE REFERENCES ventas(id) ON DELETE RESTRICT,
    responsable_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    observaciones TEXT
);
CREATE INDEX IF NOT EXISTS idx_finanzas_fecha_tipo ON movimientos_financieros(fecha DESC, tipo);

COMMIT;
